"""Generate pinned Unicode 18 ranges; no dependency on the runtime's Unicode version."""
from pathlib import Path
import hashlib,json
root=Path(__file__).parent
ucd=root.parent/'ucd'
flags=bytearray(0x110000)
start=None
for line in (ucd/'UnicodeData.txt').read_text().splitlines():
    cols=line.split(';'); cp=int(cols[0],16); name=cols[1]; cat=cols[2]
    bits=(1 if cat[0] in 'LMNPS' else 0) | (2 if cat[0] in 'LMNPS' or cat=='Zs' else 0)
    if name.endswith(', First>'): start=cp; continue
    lo=start if name.endswith(', Last>') else cp
    flags[lo:cp+1]=bytes([bits])*(cp-lo+1); start=None
for line in (ucd/'DerivedCoreProperties.txt').read_text().splitlines():
    text=line.split('#')[0].strip()
    if not text: continue
    span,prop,*_=map(str.strip,text.split(';'))
    if prop!='Default_Ignorable_Code_Point':continue
    ab=span.split('..'); a=int(ab[0],16); b=int(ab[-1],16)
    for cp in range(a,b+1):flags[cp]&=2
ranges=[]; i=0
while i<len(flags):
    j=i+1
    while j<len(flags) and flags[j]==flags[i]:j+=1
    if flags[i]:ranges.append([i,j,flags[i]])
    i=j
hashes={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in ucd.iterdir() if p.suffix=='.txt'}
(root/'unicode18.ts').write_text('// Generated by build_unicode.py from Unicode 18.0.0. See ../ucd/LICENSE.txt.\n// Inputs: '+json.dumps(hashes)+'\nconst unicodeFlags = new Uint8Array(0x110000);\nfor (const [a,b,v] of '+json.dumps(ranges,separators=(',',':'))+') unicodeFlags.fill(v,a,b);\nexport function sciCharacter(cp: number): boolean { return !!(unicodeFlags[cp] & 1); }\nexport function graphicCharacter(cp: number): boolean { return !!(unicodeFlags[cp] & 2); }\n')
print(len(ranges),'ranges',hashes)
